WITH RankedPolicies AS
(    SELECT DISTINCT
        t.Policy_ref,
        p.PolicyNumber,
        p.PolicyStatus,
        CASE 
            WHEN t.Status = 'Voided' AND t.Type IN ('Cancellation', 'Reinstate') THEN 'Voided'
            ELSE t.Status
